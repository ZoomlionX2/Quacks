    # The color of each ingredient
    WHITE = "white"     # Pea
    GREEN = "green"     # Spider
    BLUE = "blue"       # Skull
    RED = "red"         # Mushroom
    YELLOW = "yellow"   # Mandrake
    ORANGE = "orange"   # Pumpkin
    PURPLE = "purple"   # Ghost
    BLACK = "black"     # Moth